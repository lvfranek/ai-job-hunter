type OneOf<T> = T | T[];

export interface EvalCase {
  id: string;
  candidate: CandidateId;
  /** Why this is the right answer, in one or two sentences. */
  why: string;
  posting: { title: string; company: string; location: string | null; description: string };
  expect: {
    chance: OneOf<Chance>;
    /** Must match the blocker or one of the caps. */
    reason?: RegExp;
    arrangement?: OneOf<WorkArrangement | null>;
    contract?: OneOf<ContractForm>;
    years?: OneOf<number | null>;
    level?: OneOf<PostingLevel>;
    workTime?: OneOf<WorkTime | null>;
    /** The first requirement whose text matches must have this status; "absent" = none may match. */
    requirements?: Array<{ match: RegExp; status: OneOf<RequirementStatus> | "absent" }>;
  };
}

